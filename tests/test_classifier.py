"""Product type from the name: 1 chicken/poultry, 2 fish, 3 meat, 4 vegetarian.

The names are real VkusVill dishes that the keyword rules used to get wrong
(2026-10-26: meat balls, ham and sausage dishes were landing in «Вегетарианское»)."""
import pytest

from src.rest.classifier import classify_product

CHICKEN, FISH, MEAT, VEG = 1, 2, 3, 4


@pytest.mark.parametrize("name", [
    "Ежики мясные с отварной гречкой",
    "Салат \"Оливье\" с колбасой",
    "Вкусмаффин с ветчиной, сыром и яйцом",
    "Омлет с ветчиной, сыром, томатами черри и зеленью",
    "Суп \"Фо-бо\" с телятиной",
    "Суп Фо Бо, 580 г",
    "Котлеты Домашние с картофельным пюре",
    "Колбаска баварская, вес СП",
    "Солянка \"по-домашнему\"",
    "Борщ с говядиной",
    "Блинчики с ветчиной и сыром",
    "Биточки куриные с беконом",       # pork in a chicken dish is still meat
    "Оладьи печеночные, 300 г",
    "Паста \"Болоньезе\"",
    "Паста \"Карбонара\"",
    "Суп \"Гороховый\" с копчёностями",
    "Тефтели с картофельным пюре",      # no poultry anywhere → meat by default
    "Яичница глазунья с пикантной сосиской и томатами",
    "Блины с мясом",
    "Макароны по-флотски",
    "Биточки куриные с беконом",
])
def test_meat_dishes_are_meat(name):
    assert classify_product(name, "") == MEAT


@pytest.mark.parametrize("name", [
    "Котлета куриная с картофельным пюре",
    "Сосиски куриные с картофельным пюре",
    "Макароны отварные с сосисками из птицы (3 шт)",
    "Мини-чиабатта с куриной ветчиной, омлетом и сыром (2 шт)",
    "Кесадилья с ветчиной из индейки и сыром",
    "Паста Орзо с куриными фрикадельками",
    "Котлета из птицы с брокколи и соусом",
    "Стейк из индейки с овощами гриль и брокколи",
    "Пельмени с курицей",
    "Биточки курин. с цукини с пюре из батата",
    "Салат \"Цезарь\" с курицей и пекинской капустой",
    "Утка по-пекински с блинчиками",
    "Салат с мясом индейки и гранатовым соусом",
    "Голубцы ленивые из мяса птицы, 600 г",
    "Бефстроганов из курицы с картофельным пюре",
    "Пицца \"Чикен Песто\", охлажденная",
    "Мясо по-французски из индейки",
    "Куриное филе запеченное с кабачками",
    "Оладьи куриные с кабачком, 130 г",
    "Жаркое из картофеля с грибами, курицей и сливочным соусом",
    "Стейк из тыквы с куриным рулетом с курагой и шпинатом",
])
def test_poultry_dishes_are_chicken(name):
    assert classify_product(name, "") == CHICKEN


@pytest.mark.parametrize("name", [
    "Котлетки рыбные с запеченными овощами",
    "Трубочки с яйцом и копченым минтаем, 4 шт",
    "Стейк из лосося с овощами",
    "Паста Орзо с креветками",
    "Ролл \"Филадельфия\" классическая",
    "Салат \"Крабовый\"",
    "Уха по-фински",
    "Лавандовый ролл \"Бали\"",
    "Сэндвич ролл с запеченным тунцом",
])
def test_fish_dishes_are_fish(name):
    assert classify_product(name, "") == FISH


@pytest.mark.parametrize("name", [
    "Растительная котлета со стейком из тыквы и кунжутным соусом",
    "Фрикадельки растительные, вес СП",
    "Лаваш в красном с растительной котлетой",
    "Салат винегрет, 300 г",
    "Омлет с томатами и моцареллой",
    "Штрудель яблочный, веган",
    "Каша рисовая безмолочная на кокосе, 250 г",
    "Пирожки постные с рисом и грибами, 3 шт",
    "Немясной люля-кебаб с рисом и томатным соусом",
    "Биточки морковные",
    "Стейк из тыквы с тимьяном, чесноком и розмарином",
    "Десерт шоколадный с кусочками печенья и миндаля",   # «печенье» is not «печень»
    "Печенье-кукис \"Арахис-халва\"",
    "Суп \"Том ям\" вегетарианский",
    "Лапша гречневая с цукини и ореховым соусом",
    "Кабачки фаршированные грибами",
    "Салат Кобб с имбирным соусом",
])
def test_everything_else_is_vegetarian(name):
    assert classify_product(name, "") == VEG


def test_the_description_counts_too():
    assert classify_product("Паста Болоньезе", "Соус из говядины и томатов") == MEAT
